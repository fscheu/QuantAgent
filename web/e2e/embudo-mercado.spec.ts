import { test, expect } from '@playwright/test'
import { currentCycle, cycleReceipts, cycles, etfCandles, funnel, history, hypotheses, hypothesisDetail, marketClock, marketPage, reviewRule } from '../src/mocks/data'
async function openMock(page: import('@playwright/test').Page, path: string) {
  await page.route('**/api/**', route => {
    const url = new URL(route.request().url()), p = url.pathname
    const receipt = p.match(/\/api\/funnel\/cycles\/([^/]+)\/receipt/)
    const detail = p.match(/\/api\/hypotheses\/([^/]+)/)
    const body = p === '/api/funnel' ? funnel : p === '/api/funnel/cycles' ? cycles : p.endsWith('/cycles/current') ? currentCycle : receipt ? cycleReceipts.find(item => item.cycle === receipt[1]) : p === '/api/funnel/review' ? reviewRule : p === '/api/funnel/history' ? history : p === '/api/hypotheses' ? hypotheses : detail ? hypothesisDetail : p === '/api/market' ? marketPage : p === '/api/market/clock' ? marketClock : p.includes('/candles') ? etfCandles : p === '/api/market/series' ? (url.searchParams.get('symbols') ?? '').split(',').map(symbol => ({ symbol, points: [{ date: '2026-10-01', value: 100 }] })) : undefined
    return body === undefined ? route.continue() : route.fulfill({ json: body })
  })
  await page.goto(path)
}
test('navegación por teclado mantiene destino activo y foco visible', async ({ page }) => {
  await openMock(page, '/?mock=1')
  const nav = page.getByRole('navigation', { name: 'Secciones' })
  await expect(nav.getByRole('link', { name: 'Inicio' })).toBeVisible()
  await page.keyboard.press('Tab')
  await expect(nav.getByRole('link', { name: 'Inicio' })).toBeFocused()
  await expect(nav.getByRole('link', { name: 'Inicio' })).toHaveCSS('outline-style', 'solid')
  await page.keyboard.press('Tab'); await page.keyboard.press('Tab'); await page.keyboard.press('Tab')
  await expect(nav.getByRole('link', { name: 'Embudo' })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page).toHaveURL(/\/embudo(?:\?|$)/)
  await expect(nav.getByRole('link', { name: 'Embudo' })).toHaveAttribute('aria-current', 'page')
  await page.keyboard.press('Tab'); await page.keyboard.press('Enter')
  await expect(page).toHaveURL(/\/mercado(?:\?|$)/)
  await expect(nav.getByRole('link', { name: 'Mercado' })).toHaveAttribute('aria-current', 'page')
})
test('embudo muestra datos, filtros, recibo, ficha y estados independientes', async ({ page }) => {
  await openMock(page, '/embudo?mock=1')
  await expect(page.getByRole('heading', { name: 'Embudo' })).toBeVisible()
  await expect(page.getByLabel('Regla de revisión')).not.toBeEmpty()
  await expect(page.getByRole('region', { name: 'Resumen del embudo' })).toContainText('hipótesis')
  await expect(page.getByRole('heading', { name: 'Motivos de descarte' })).toBeVisible()
  await expect(page.getByRole('region', { name: 'Hipótesis' }).getByText(/.+/).first()).toBeVisible()
  const cycle = page.locator('.qa-cycle-filter select')
  await cycle.selectOption('2026-10')
  await expect(page).toHaveURL(/ciclo=2026-10/)
  await expect(page.getByRole('group', { name: /Período/ })).toBeDisabled()
  await openMock(page, '/embudo/ciclo/2026-10?mock=1')
  await expect(page.getByRole('heading', { name: /Recibo · 2026-10/ })).toBeVisible()
  await openMock(page, '/embudo?mock=1')
  await page.locator('.qa-hypothesis-card').first().click()
  await expect(page).toHaveURL(/\/hipotesis\//)
  await expect(page.getByRole('heading').first()).toBeVisible()
  await openMock(page, '/embudo?mock=1')
  await page.route('**/api/hypotheses**', route => route.fulfill({ json: [] }))
  await page.reload()
  await expect(page.getByRole('status')).toContainText('No hay hipótesis')
  await page.unroute('**/api/hypotheses**')
  await page.route('**/api/funnel**', route => new URL(route.request().url()).pathname === '/api/funnel' ? route.abort() : route.continue())
  await page.reload()
  await expect(page.getByText('No pudimos cargar resumen del embudo.')).toBeVisible()
  await expect(page.getByLabel('Regla de revisión')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Reintentar' }).first()).toBeVisible()
})
test('mercado, detalle ETF, error, dato viejo y accesibilidad manual', async ({ page }) => {
  await openMock(page, '/mercado?mock=1')
  await expect(page.getByRole('heading', { name: 'Mercado' })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Régimen', exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Sectores' })).toBeVisible()
  await expect(page.getByRole('table', { name: 'Retornos, estado y posiciones de sectores' })).toBeVisible()
  await page.getByRole('button', { name: 'Mapa de calor' }).click()
  await expect(page.getByRole('table', { name: /Mapa de calor sectorial/ })).toBeVisible()
  await page.getByRole('button', { name: 'Tabla' }).focus()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('heading', { name: 'Macro' })).toBeVisible()
  await expect(page.getByLabel('Serie próximamente').first()).toBeVisible()
  await expect(page.getByRole('heading', { name: 'ETFs' })).toBeVisible()
  const etfs = page.getByRole('table', { name: 'ETFs por clase de activo' })
  await expect(etfs.getByRole('row')).toHaveCount(30)
  await expect(page.getByRole('heading', { name: 'Próximos eventos' })).toBeVisible()
  for (const symbol of ['IWM', 'XLB', 'XLE', 'XLF']) await page.getByRole('checkbox', { name: `Comparar ${symbol}` }).check()
  await expect(page.getByRole('status')).toContainText('Máximo de 5 ETFs')
  await etfs.getByRole('row').filter({ hasText: 'SPY' }).click()
  await expect(page).toHaveURL(/\/mercado\/etf\/SPY/)
  await expect(page.getByRole('table', { name: /Datos diarios de SPY/ })).toBeVisible()
  await page.getByRole('button', { name: '3M' }).click()
  await expect(page.getByRole('button', { name: '3M' })).toHaveAttribute('aria-pressed', 'true')
  await openMock(page, '/mercado?mock=1')
  await page.route('**/api/market', route => route.fulfill({ json: { ...marketPage, as_of: { ...marketPage.as_of, stale: true, missing_sessions: ['2026-10-29'] } } }))
  await page.reload()
  await expect(page.getByText('Datos de mercado desactualizados')).toBeVisible()
  await page.unroute('**/api/market')
  await page.route('**/api/market**', route => new URL(route.request().url()).pathname === '/api/market' ? route.abort() : route.continue())
  await page.reload()
  await expect(page.getByText('No pudimos cargar el mercado.')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Reintentar' })).toBeVisible()
})
test.describe('zoom de alta densidad', () => {
  test.use({ viewport: { width: 640, height: 480 }, deviceScaleFactor: 2 })
  for (const path of ['/embudo?mock=1', '/mercado?mock=1']) {
    test(`${path} sin scroll horizontal a 200 %`, async ({ page }) => {
    await page.setViewportSize({ width: 640, height: 480 })
    await openMock(page, path)
    await expect(page.getByRole('main')).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(640)
  })
  }
})
